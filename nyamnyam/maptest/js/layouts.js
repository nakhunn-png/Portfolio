// 도면을 칸 배열로 바꾼다. kind: 0 빈칸, 1 바닥, 2 가구 / room: 방 번호(-1 = 복도·바깥)
export function compileLayout(id) {
  const L = LAYOUTS[id] || LAYOUTS[1], W = L.W, H = L.H;
  const kind = new Uint8Array(W * H), room = new Int8Array(W * H).fill(-1);
  const fixtures = [];
  let start = null, exit = null;
  const inb = (x, y) => x >= 0 && y >= 0 && x < W && y < H;
  const rect = (x, y, w, h, f) => { for (let Y = y; Y < y + h; Y++) for (let X = x; X < x + w; X++) if (inb(X, Y)) f(Y * W + X); };
  const b = {
    room(rid, x, y, w, h) { rect(x, y, w, h, (i) => { kind[i] = 1; room[i] = rid; }); },
    cut(x, y, w, h) { rect(x, y, w, h, (i) => { kind[i] = 0; room[i] = -1; }); },
    hall(wd, ...pts) {
      for (let k = 1; k < pts.length; k++) {
        const [ax, ay] = pts[k - 1], [bx, by] = pts[k];
        // 가로 구간은 아래로, 세로 구간은 오른쪽으로 폭만큼 넓힌다
        const x0 = Math.min(ax, bx), y0 = Math.min(ay, by);
        const w = ay === by ? Math.abs(bx - ax) + 1 : wd, h = ay === by ? wd : Math.abs(by - ay) + 1;
        rect(x0, y0, w, h, (i) => { if (kind[i] === 0) kind[i] = 1; });
      }
    },
    fix(type, x, y, w, h, hallSide) { fixtures.push({ type, x, y, w, h, hallSide: !!hallSide }); rect(x, y, w, h, (i) => { kind[i] = 2; }); },
    start(x, y) { start = { x, y }; },
    exit(x, y) { exit = { x, y }; },
  };
  L.build(b);
  return { W, H, kind, room, fixtures, start, exit };
}
